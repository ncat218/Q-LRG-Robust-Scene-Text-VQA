def merged_train(manifests):
    check_disjoint(manifests.values())
    records=sorted(manifests['train_inner']['images']+manifests['val_inner']['images'],key=lambda x:x['image_id'])
    return {'schema':2,'split':'official_train_refit','images':records,
            'source_hashes':{k:object_hash(v) for k,v in manifests.items()},
            'policy':'Selection split merged only after validation chooses a duration; official_val excluded.'}


def validate_config(config):
    if config['initialization']!='fresh_same_seed' or config['feature_disk_cache']:
        raise ValueError('Use fresh matched initialization and no disk feature cache')
    for key in ('seed','max_epochs','min_epochs','patience','accumulate','checkpoint_every_updates'):
        if type(config[key]) is not int or config[key] < (0 if key=='seed' else 1):
            raise ValueError(f'Invalid integer setting {key}')
    if config['min_epochs']>config['max_epochs'] or not 0<config['evaluate_every_epoch_fraction']<=1:
        raise ValueError('Invalid validation cadence or epoch limits')
    for key in ('learning_rate','min_delta_pp','clean_tolerance_pp'):
        if not math.isfinite(config[key]) or config[key]<=0:raise ValueError(f'Invalid {key}')


def prepare_proposals(launch,paths,model_config,records,output):
    from scripts.sdrpn_runtime import selector_environment
    from scripts.selector_assets import MODELS, PROCESSOR, UPSTREAM_REVISION
    assets=Path(launch['selector_assets'])
    name,revision=MODELS['visionrl2_7b']
    checkpoint=assets/'hub'/('models--'+name.replace('/','--'))/'snapshots'/revision
    processor=assets/'hub'/('models--'+PROCESSOR[0].replace('/','--'))/'snapshots'/PROCESSOR[1]
    vendor=assets/'source'
    for path in (checkpoint/'config.json',processor/'chat_template.json',vendor/'qwen_src'):
        if not path.exists():raise FileNotFoundError(path)
    actual=subprocess.check_output(['git','-C',str(vendor),'rev-parse','HEAD'],text=True).strip()
    if actual!=UPSTREAM_REVISION:raise ValueError('Selector vendor revision changed')
    request={'textvqa':str(paths['textvqa']),'prompt':model_config['prompt'],'seed':launch['train_config']['seed'],
             'images':[{**{k:im[k] for k in ('image_id','image_rel','image_sha256','size','exif_orientation')},
                        'questions':[{'question_id':q['question_id'],'query':q['question']} for q in im['questions']]}
                       for im in records]}
    source={'request_hash':object_hash(request),'model':name,'revision':revision,
            'vendor_revision':actual,'config_sha256':sha256(checkpoint/'config.json'),
            'weight_index_sha256':sha256(checkpoint/'model.safetensors.index.json'),
            'padding_per_side':.2,'labels_in_request':False}
    directory=output/'proposals';directory.mkdir(exist_ok=True)
    with FileLock(str(directory/'.lock'),timeout=0):
        if (directory/'source.json').exists() and read_json(directory/'source.json')!=source:
            raise ValueError('Existing proposal source differs')
        write_json(directory/'source.json',source)
        write_json(directory/'request.json',request)
        env=selector_environment(launch)
        env.update(HF_HUB_OFFLINE='1',TRANSFORMERS_OFFLINE='1',PYTHONDONTWRITEBYTECODE='1',
                   XDG_CACHE_HOME=str(output/'.selector-cache'))
        subprocess.run([str(Path(launch['sdrpn_env'])/'bin/python'),'-B',
                        str(Path(launch['repo'])/'scripts/visionrl2_select.py'),
                        '--request',str(directory/'request.json'),'--output',str(directory),
                        '--vendor',str(vendor),'--checkpoint',str(checkpoint),'--processor',str(processor)],
                       cwd=launch['repo'],env=env,check=True)
    return source


class Features:
    """Keep only the current pair. Crop is selected on LR4 and reused for CLEAN."""

    def __init__(self,model,root,view,output):
        self.model,self.root,self.view,self.output=model,root,view,output
        self.current=None;self.current_image=None

    def load(self,image,question):
        key=(image['image_id'],None if self.view=='full' else question['question_id'])
        if key==self.current:return
        if image['image_id']!=self.current_image:
            self.pixels=paired_images(self.root,image)
            self.current_image=image['image_id']
            if self.view=='crop':
                p=self.output/'proposals'/f"{object_hash(image['image_id'])[:24]}.json"
                self.proposal=read_json(p)
                if (self.proposal['image_id']!=image['image_id'] or
                    self.proposal['lr4_sha256']!=hashlib.sha256(self.pixels[1].tobytes()).hexdigest() or
                    set(self.proposal['questions'])!={str(q['question_id']) for q in image['questions']}):
                    raise ValueError('Proposal pixels or questions differ from the training example')
        clean,lr4=self.pixels
        self.box=None
        if self.view=='crop':
            raw=self.proposal['questions'][str(question['question_id'])]['box']
            self.box=padded_box(raw,lr4.size,.2) if raw is not None else None
            if self.box is not None:
                clean,lr4=clean.crop(self.box),lr4.crop(self.box)
        self.images={'CLEAN':clean,'LR4':lr4}
        prompts={k:self.model.prepare(im,question['question']) for k,im in self.images.items()}
        assert_aligned(prompts['CLEAN'],prompts['LR4'])
        with torch.no_grad():self.features={k:self.model.encode(b).detach() for k,b in prompts.items()}
        self.thw=prompts['CLEAN']['image_grid_thw'][0].tolist()
        self.grid=image_grid(self.thw)
        self.current=key

    def prompt(self,condition,question):
        batch=self.model.prepare(self.images[condition],question)
        if batch['image_grid_thw'][0].tolist()!=self.thw:raise ValueError('Feature grid changed')
        return batch


def save_checkpoint(path,adapter,optimizer,binding,offset,policy,history):
    buffer=io.BytesIO()
    torch.save({'binding':object_hash(binding),'arm':'S1b','adapter':adapter.state_dict(),
                'optimizer':optimizer.state_dict(),'examples':offset,
                'selection':policy.state_dict() if policy else None,'history':history,
                'cpu_rng':torch.get_rng_state(),'cuda_rng':torch.cuda.get_rng_state()},buffer)
    atomic_write(path,buffer.getvalue())


@torch.inference_mode()
def evaluate(model,adapter,cache,manifest,scorer,baseline=False):
    adapter.eval();rows=[]
    for image in manifest['images']:
        for question in image['questions']:
            cache.load(image,question)
            refs=scorer._compute_answer_scores(question['answers'])
            for condition in ('CLEAN','LR4'):
                base=cache.features[condition]
                value=base if baseline else adapter(base,cache.grid)[0].to(model.dtype)
                result=model.generate(cache.prompt(condition,question['question']),value)
                rows.append({'image_id':image['image_id'],'question_id':question['question_id'],
                             'condition':condition,'answer':result['answer'],
                             'score':refs.get(scorer.answer_processor(result['answer']),0.0),
                             'visual_tokens':len(base),'crop_xyxy':cache.box})
    scores={c:100*sum(r['score'] for r in rows if r['condition']==c)/(len(rows)//2) for c in ('CLEAN','LR4')}
    return scores,rows


def train_stage(model,cache,adapter,records,dev,base_config,settings,directory,binding,refit_visits=None):
    directory.mkdir(parents=True,exist_ok=True)
    if (directory/'COMPLETE.json').exists():
        done=read_json(directory/'COMPLETE.json')
        if done['binding']!=object_hash(binding):raise ValueError('Completed training binding differs')
        if sha256(directory/done['checkpoint'])!=done['checkpoint_sha256']:raise ValueError('Completed checkpoint changed')
        return done
    optimizer=torch.optim.AdamW(adapter.parameters(),lr=settings['learning_rate'],weight_decay=base_config['weight_decay'])
    examples_per_epoch=sum(len(im['questions']) for im in records)
    accumulate=settings['accumulate']
    epochs=settings['max_epochs'] if refit_visits is None else math.ceil(refit_visits/examples_per_epoch)
    examples=list(training_examples(records,epochs,settings['seed'],base_config['clean_fraction']))
    if refit_visits is not None:examples=examples[:refit_visits]
    interval=max(accumulate,round(examples_per_epoch*settings['evaluate_every_epoch_fraction']/accumulate)*accumulate)
    offset=0;history=[];policy=None
    latest=directory/'latest.pt';best=directory/'best.pt';scorer=evaluator()
    if latest.exists():
        state=torch.load(latest,map_location='cpu',weights_only=True)
        if state['binding']!=object_hash(binding):raise ValueError('Resume checkpoint differs')
        adapter.load_state_dict(state['adapter']);optimizer.load_state_dict(state['optimizer'])
        offset=state['examples'];history=state['history']
        policy=Selection(**state['selection']) if state['selection'] else None
        torch.set_rng_state(state['cpu_rng']);torch.cuda.set_rng_state(state['cuda_rng'])
        if not 0<=offset<=len(examples) or (offset!=len(examples) and offset%accumulate):
            raise ValueError('Invalid resume offset')
    elif refit_visits is None:
        baseline,rows=evaluate(model,adapter,cache,dev,scorer,baseline=True)
        write_json(directory/'baseline.json',baseline);write_jsonl(directory/'baseline_predictions.jsonl',rows)
        policy=Selection(baseline_clean=baseline['CLEAN'],clean_tolerance_pp=settings['clean_tolerance_pp'],
                         min_delta_pp=settings['min_delta_pp'],patience=settings['patience'],min_epochs=settings['min_epochs'],
                         best_lr4=baseline['LR4'],progress_lr4=baseline['LR4'])
        save_checkpoint(best,adapter,optimizer,binding,0,policy,history)
        save_checkpoint(latest,adapter,optimizer,binding,0,policy,history)
    stopping=bool(policy and offset/examples_per_epoch>=settings['min_epochs'] and policy.bad_checks>=settings['patience'])
    interrupted=[False]
    old_handler=signal.signal(signal.SIGTERM,lambda *_:interrupted.__setitem__(0,True))
    try:
        while offset<len(examples) and not stopping:
            boundary=min(len(examples),((offset//interval)+1)*interval) if refit_visits is None else len(examples)
            adapter.train()
            window=[]
            with text_training(model.model,True):
                while offset<boundary:
                    group=examples[offset:min(boundary,offset+accumulate)]
                    optimizer.zero_grad(set_to_none=True)
                    totals={'loss':0.,'feature_loss':0.,'task_loss':0.,'residual_loss':0.}
                    for image,question,condition,answer in group:
                        cache.load(image,question)
                        restored,delta=adapter(cache.features[condition],cache.grid)
                        match=F.mse_loss(restored,cache.features['CLEAN'].float())
                        tokenizer=model.processor.tokenizer
                        tokens=tokenizer.encode(answer,add_special_tokens=False)[:base_config['max_answer_tokens']]
                        tokens.append(tokenizer.eos_token_id)
                        task=teacher_forced_loss(model,cache.prompt(condition,question['question']),restored.to(model.dtype),tokens)
                        residual=delta.square().mean()
                        weight=base_config['residual_weight']+(base_config.get('clean_residual_weight',0) if condition=='CLEAN' else 0)
                        loss=task+base_config['feature_weight']*match+weight*residual
                        (loss/len(group)).backward()
                        for key,value in zip(totals,(loss,match,task,residual)):totals[key]+=float(value.detach())/len(group)
                    norm=float(torch.nn.utils.clip_grad_norm_(adapter.parameters(),base_config['max_grad_norm'],error_if_nonfinite=True))
                    if not math.isfinite(totals['loss']) or any(p.grad is not None for p in model.model.parameters()):
                        raise RuntimeError('Invalid loss or backbone gradient')
                    optimizer.step();offset+=len(group)
                    window.append(totals)
                    updates=math.ceil(offset/accumulate)
                    if updates%200==0 or offset==boundary:
                        entry={key:sum(r[key] for r in window)/len(window) for key in totals}
                        entry.update(examples=offset,epoch=offset/examples_per_epoch,grad_norm=norm,
                                     peak_cuda_bytes=torch.cuda.max_memory_allocated())
                        history.append(entry);window=[]
                        print(f"{cache.view}: {offset}/{len(examples)} visits, epoch {entry['epoch']:.3f}, loss {entry['loss']:.4f}",flush=True)
                    if updates%settings['checkpoint_every_updates']==0 or interrupted[0]:
                        save_checkpoint(latest,adapter,optimizer,binding,offset,policy,history)
                    if interrupted[0]:raise SystemExit('Saved latest checkpoint on termination; resume this run')
            optimizer.zero_grad(set_to_none=True)
            if refit_visits is None:
                scores,rows=evaluate(model,adapter,cache,dev,scorer)
                decision=policy.observe(scores['LR4'],scores['CLEAN'],offset,offset/examples_per_epoch)
                entry={'examples':offset,'epoch':offset/examples_per_epoch,**scores,**decision,
                       'best_lr4':policy.best_lr4,'best_examples':policy.best_examples,'bad_checks':policy.bad_checks}
                write_json(directory/f'eval-{offset:08d}.json',entry)
                write_jsonl(directory/'latest_predictions.jsonl',rows)
                if decision['save_best']:
                    save_checkpoint(best,adapter,optimizer,binding,offset,policy,history)
                    write_jsonl(directory/'best_predictions.jsonl',rows)
                stopping=decision['stop']
                print(f"{cache.view} validation: {entry}",flush=True)
            save_checkpoint(latest,adapter,optimizer,binding,offset,policy,history)
    finally:signal.signal(signal.SIGTERM,old_handler)
    done={'binding':object_hash(binding),'reason':'early_stopping' if stopping else 'fixed_refit_duration' if refit_visits is not None else 'epoch_cap',
          'examples':offset,'examples_per_epoch':examples_per_epoch,'epochs_completed':offset/examples_per_epoch,
          'selection':policy.state_dict() if policy else None,'checkpoint':'best.pt' if policy else 'latest.pt',
          'official_val_used_for_selection':False}
    done['checkpoint_sha256']=sha256(directory/done['checkpoint'])
    write_json(directory/'COMPLETE.json',done)
    return done


def run_view(output,view):
    launch=read_json(output/'launch.json');settings=launch['train_config'];validate_config(settings)
    paths=dataset_paths(read_config(launch['paths']))
    model_config=read_config(Path(launch['repo'])/'configs/model_qwen.yaml')
    manifests,hashes=read_s1_manifests(Path(launch['data_dir']),paths['textvqa'])
    all_train=merged_train(manifests)
    trained=verified_complete(Path(launch['s1_run'])/'s1','s1')
    if hashes!=trained['dataset_hashes'] or model_config!=trained['shared']['model']:
        raise ValueError('Training data or Qwen differs from job 11305')
    base_config={**trained['config'],'seed':settings['seed'],'learning_rate':settings['learning_rate'],
                 'accumulate':settings['accumulate']}
    records=manifests['train_inner']['images'];dev=manifests['val_inner']
    if launch.get('smoke_images'):
        records=records[:launch['smoke_images']];dev={**dev,'images':dev['images'][:launch['smoke_images']]}
        all_train={**all_train,'images':records+dev['images']}
        settings={**settings,'max_epochs':1,'min_epochs':1,'evaluate_every_epoch_fraction':1.0,'refit_official_train':False}
    destination=output/view;destination.mkdir(exist_ok=True)
    with FileLock(str(destination/'.run.lock'),timeout=0):
        proposal_source=prepare_proposals(launch,paths,model_config,all_train['images'],output) if view=='crop' else None
        torch.manual_seed(settings['seed']);torch.backends.cuda.matmul.allow_tf32=False
        model=Qwen(model_config,paths['hf_hub'])
        binding={'stage':'s1_convergence','view':view,'settings':settings,'base_config':base_config,
                 'shared':runtime_shared(paths,model_config),'train_manifest_hash':object_hash(records),
                 'dev_manifest_hash':object_hash(dev),'official_train_hash':object_hash(all_train),
                 'source_11305_binding':object_hash(trained),'proposal_source':proposal_source,
                 'worker_sha256':sha256(Path(__file__)),'policy_sha256':sha256(Path(__file__).with_name('convergence_policy.py'))}
        bind(destination,binding)
        write_json(destination/'train_manifest.json',{'images':records})
        write_json(destination/'official_train_manifest.json',all_train)
        adapter=make_adapter(model,'S1b',base_config)
        cache=Features(model,paths['textvqa'],view,output)
        # Prove zero-initialized restoration preserves the native prompt, including its query.
        first=records[0];question=first['questions'][0];cache.load(first,question)
        prompt=cache.prompt('LR4',question['question'])
        with torch.no_grad():
            restored=adapter(cache.features['LR4'],cache.grid)[0].to(model.dtype)
            if not torch.equal(model.prefill_logits(prompt),model.prefill_logits(prompt,restored)):
                raise RuntimeError('Initial S1b identity gate failed')
        # Verify the answer gradient crosses the frozen LLM before a long validation pass.
        with text_training(model.model,True):
            restored,delta=adapter(cache.features['LR4'],cache.grid)
            tokens=model.processor.tokenizer.encode(question['answers'][0].strip(),add_special_tokens=False)[:base_config['max_answer_tokens']]
            tokens.append(model.processor.tokenizer.eos_token_id)
            loss=teacher_forced_loss(model,prompt,restored.to(model.dtype),tokens)
            loss=loss+base_config['feature_weight']*F.mse_loss(restored,cache.features['CLEAN'].float())
            loss.backward()
            norm=float(torch.nn.utils.clip_grad_norm_(adapter.parameters(),1.,error_if_nonfinite=True))
            if norm<=0 or any(p.grad is not None for p in model.model.parameters()):
                raise RuntimeError('S1b frozen-backbone gradient probe failed')
            adapter.zero_grad(set_to_none=True)
        write_json(destination/'gradient_probe.json',{'passed':True,'grad_norm':norm,'loss':float(loss.detach())})
        del loss,restored,delta
        selected=train_stage(model,cache,adapter,records,dev,base_config,settings,destination/'selection',binding)
        result={'selection':selected,'refit':None,'official_val_evaluated':False}
        if settings['refit_official_train']:
            visits=selected['selection']['best_examples']
            count=sum(len(im['questions']) for im in all_train['images'])
            target=round(visits/selected['examples_per_epoch']*count/settings['accumulate'])*settings['accumulate']
            adapter=make_adapter(model,'S1b',base_config) # restart; refit uses no dev-based decisions
            refit_binding={**binding,'selected_examples':visits,'selected_checkpoint_sha256':selected['checkpoint_sha256'],
                           'refit_visits':target,'refit_rule':'same selected fractional epochs over all official_train'}
            if target:
                result['refit']=train_stage(model,cache,adapter,all_train['images'],None,base_config,settings,
                                            destination/'refit',refit_binding,refit_visits=target)
            else:result['refit']={'skipped':'No trained checkpoint beat the eligible zero-initialized baseline.'}
        write_json(destination/'summary.json',result)
        write_json(destination/'COMPLETE.json',{'binding':object_hash(binding),'summary_sha256':sha256(destination/'summary.json')})


def run(output):
    if not os.environ.get('SLURM_JOB_ID'):raise RuntimeError('Training requires a Slurm GPU allocation')
    launch=read_json(output/'launch.json')
    if launch['study']!='s1_convergence':raise ValueError('Wrong training study')
    views=('full','crop') if launch['train_view']=='both' else (launch['train_view'],)
    # Separate child processes release the GPU completely between the selector and readers/views.
    for view in views:
        subprocess.run([sys.executable,'-B','-m','scripts.s1_convergence',str(output),'--worker-view',view],check=True)
    write_json(output/'COMPLETE.json',{'stage':'s1_convergence','views':list(views),
                                     'summaries':{v:sha256(output/v/'summary.json') for v in views}})


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output',type=Path)
    parser.add_argument('--worker-view',choices=('full','crop'))
    args=parser.parse_args()
    if args.worker_view:run_view(args.output,args.worker_view)
    else:run(args.output)
